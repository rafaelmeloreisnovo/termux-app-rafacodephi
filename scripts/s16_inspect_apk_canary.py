#!/usr/bin/env python3
"""S16 hosted APK forensic gate: source-bound, no installation, no uploads.

This is BUILD_TOOLING, never linked into RAFAELIA PURE_CORE. It checks a debug
artifact generated by Gradle, not physical execution or source authorship.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
import sys
import tempfile
from zipfile import ZipFile, BadZipFile

PACKAGE = "com.termux.rafacodephi"
MODULE = "libtermux_rafaelia_middleware_s15.so"
EXPECTED = {"armeabi-v7a": "ARM", "arm64-v8a": "AArch64"}
ALLOWED_NEEDED = {"libc.so", "libm.so", "libdl.so", "liblog.so", "libandroid.so"}
SHA = re.compile(r"^[0-9a-f]{40}$")

def fail(reason):
    raise RuntimeError(reason)

def command(args):
    proc = subprocess.run(args, capture_output=True, text=True, check=False)
    if proc.returncode:
        fail("COMMAND_FAILED " + args[0] + " status=" + str(proc.returncode)
             + " diagnostics=" + proc.stderr[-320:].replace("\n", " "))
    return proc.stdout

def sha256(path):
    h = hashlib.sha256()
    with path.open("rb") as f:
        for buf in iter(lambda: f.read(1 << 20), b""):
            h.update(buf)
    return h.hexdigest()

def validate_one(apk, aapt, apksigner, readelf, temp):
    apk = apk.resolve(strict=True)
    package_info = command([aapt, "dump", "badging", str(apk)])
    match = re.search(r"^package: name='([^']+)'", package_info, re.M)
    if not match or match.group(1) != PACKAGE:
        fail("PACKAGE_IDENTITY_MISMATCH " + apk.name)
    signature = command([apksigner, "verify", "--verbose", str(apk)])
    if "Verifies" not in signature:
        fail("SIGNATURE_RECEIPT_EMPTY " + apk.name)

    try:
        with ZipFile(apk) as z:
            bad = z.testzip()
            if bad is not None:
                fail("ZIP_CRC_MISMATCH " + apk.name + " " + bad)
            names = set(z.namelist())
            if "classes.dex" not in names:
                fail("DEX_MISSING " + apk.name)
            libs = {abi: f"lib/{abi}/{MODULE}" for abi in EXPECTED}
            found = [abi for abi, key in libs.items() if key in names]
            if not found:
                fail("PINNED_MIDDLEWARE_NOT_PACKAGED " + apk.name)
            bootstrap = [n for n in names if n.startswith("lib/") and "bootstrap" in n.lower() and n.endswith(".so")]
            if not bootstrap:
                fail("BOOTSTRAP_ELF_NOT_PACKAGED " + apk.name)
            validated = []
            for abi in found:
                filename = libs[abi]
                target = temp / (apk.stem + "-" + abi + ".so")
                with z.open(filename) as src, target.open("wb") as dest:
                    for part in iter(lambda: src.read(1 << 20), b""):
                        dest.write(part)
                hdr = command([readelf, "-h", str(target)])
                if not re.search(r"Machine:\s*" + EXPECTED[abi] + r"(?:\s|$)", hdr):
                    fail("ELF_MACHINE_MISMATCH " + apk.name + " " + abi)
                dyn = command([readelf, "-d", str(target)])
                needed = set(re.findall(r"\(NEEDED\).*?\[([^\]]+)\]", dyn))
                if needed - ALLOWED_NEEDED:
                    fail("UNREVIEWED_ANDROID_DYNAMIC_DEPS " + apk.name + " " + repr(sorted(needed)))
                validated.append({"abi": abi, "elf_sha256": sha256(target),
                                  "elf_bytes": target.stat().st_size,
                                  "dt_needed": sorted(needed)})
            return {"name": apk.name, "bytes": apk.stat().st_size,
                    "sha256": sha256(apk), "package": PACKAGE,
                    "debug_signature_verified_by_apksigner": True,
                    "bootstrap_so_present": True,
                    "dex_present": True,
                    "middleware_elf": validated}
    except BadZipFile as exc:
        fail("BAD_APK_ZIP " + apk.name + ": " + type(exc).__name__)

def main():
    p=argparse.ArgumentParser()
    p.add_argument("--dir", type=Path, required=True)
    p.add_argument("--output", type=Path, required=True)
    p.add_argument("--head", required=True)
    p.add_argument("--aapt", default="aapt")
    p.add_argument("--apksigner", default="apksigner")
    p.add_argument("--readelf", default="readelf")
    a=p.parse_args()
    if not SHA.fullmatch(a.head):
        fail("INVALID_EXACT_HEAD")
    local_head=command(["git", "rev-parse", "HEAD"]).strip()
    if local_head != a.head:
        fail("CHECKOUT_HEAD_MISMATCH")
    if a.output.exists():
        fail("APPEND_ONLY_OUTPUT_ALREADY_EXISTS")
    if not a.dir.is_dir():
        fail("APK_OUTPUT_DIR_MISSING")
    apks=sorted(a.dir.rglob("*.apk"))
    if not apks:
        fail("NO_APK_CREATED")
    with tempfile.TemporaryDirectory(prefix="s16-apk-inspection-") as scratch:
        data=[validate_one(apk,a.aapt,a.apksigner,a.readelf,Path(scratch)) for apk in apks]
    abis={x["abi"] for entry in data for x in entry["middleware_elf"]}
    if abis != set(EXPECTED):
        fail("REQUIRED_TWO_ABIS_NOT_PACKAGED " + str(sorted(abis)))
    report={
        "schema":"rafaelia.s16.apk_canary_inspection.v1",
        "exact_head":a.head,
        "gate":"PASS_SCOPED_APK_STATIC_ONLY",
        "package":PACKAGE,
        "expected_abismask":sorted(EXPECTED),
        "source_core_sha1_git_blob":"e46b1e24191f901edf91d6ce4c5003fa5d74438f",
        "middleware_enabled_for_this_debug_build":True,
        "bootstrap_profile":"BRIDGE_ONLY_DIAGNOSTIC_NOT_REAL_PKG",
        "apt_pkg_proot_operational":False,
        "suitable_for_installation_or_release":False,
        "source_l0_executed":False,
        "physical_phone_tested":False,
        "bootstrap_runtime_tested":False,
        "production_install_authorized":False,
        "rights_and_licence_approved":False,
        "claim_allowed":False,
        "apk_count":len(data),
        "apk_receipts":data,
    }
    a.output.parent.mkdir(parents=True,exist_ok=True)
    data_bytes=(json.dumps(report,sort_keys=True,indent=2)+"\n").encode("utf8")
    with a.output.open("xb") as f: f.write(data_bytes)
    print("PASS_SCOPED_STATIC_APK sha256_receipt="+hashlib.sha256(data_bytes).hexdigest())
    print("Android physical/runtime/keyboard/pkg/apt/rollback: TOKEN_VAZIO_NOT_RUN")

if __name__=="__main__":
    try: main()
    except (RuntimeError, FileNotFoundError, OSError, KeyError, ValueError) as e:
        print("FAIL_CLOSED: "+str(e),file=sys.stderr)
        raise SystemExit(2)
