#include "../src/bootstrap/receipt_sealer_real.c"

static int eq32(const uint8_t *a, const uint8_t *b) {
    for (uint32_t i = 0u; i < 32u; i++) if (a[i] != b[i]) return 0;
    return 1;
}

static int sha_case(const uint8_t *data, uint32_t len, const uint8_t expected[32]) {
    struct sha256_ctx ctx;
    uint8_t out[32];
    sha256_init(&ctx);
    sha256_update(&ctx, data, len);
    sha256_finalize(&ctx, out);
    return eq32(out, expected);
}

int main(void) {
    static const uint8_t E0[32] = {0xe3,0xb0,0xc4,0x42,0x98,0xfc,0x1c,0x14,0x9a,0xfb,0xf4,0xc8,0x99,0x6f,0xb9,0x24,0x27,0xae,0x41,0xe4,0x64,0x9b,0x93,0x4c,0xa4,0x95,0x99,0x1b,0x78,0x52,0xb8,0x55};
    static const uint8_t EABC[32] = {0xba,0x78,0x16,0xbf,0x8f,0x01,0xcf,0xea,0x41,0x41,0x40,0xde,0x5d,0xae,0x22,0x23,0xb0,0x03,0x61,0xa3,0x96,0x17,0x7a,0x9c,0xb4,0x10,0xff,0x61,0xf2,0x00,0x15,0xad};
    static const uint8_t EA56[32] = {0xb3,0x54,0x39,0xa4,0xac,0x6f,0x09,0x48,0xb6,0xd6,0xf9,0xe3,0xc6,0xaf,0x0f,0x5f,0x59,0x0c,0xe2,0x0f,0x1b,0xde,0x70,0x90,0xef,0x79,0x70,0x68,0x6e,0xc6,0x73,0x8a};
    static const uint8_t ABC[3] = {'a','b','c'};
    uint8_t a56[56];
    struct Receipt receipt;

    for (uint32_t i = 0u; i < 56u; i++) a56[i] = (uint8_t)'a';

    if (!sha_case((const uint8_t *)"", 0u, E0)) return 1;
    if (!sha_case(ABC, 3u, EABC)) return 2;
    if (!sha_case(a56, 56u, EA56)) return 3;
    if (crc32c_compute((const uint8_t *)"123456789", 9u) != 0xE3069283u) return 4;
    if (seal_receipt_complete(&receipt, "abc", 3u) != 0) return 5;
    if (receipt.magic != 0xDEADBEEFu || receipt.crc32c != 0x364B3FB7u) return 6;
    if (!eq32(receipt.sha256, EABC)) return 7;
    if (verify_receipt_sha256(&receipt, "abc", 3u) != 0) return 8;
    return 0;
}
